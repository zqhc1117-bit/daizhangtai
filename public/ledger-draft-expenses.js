export const expenseAliases = expenseTypes.flatMap(([aliases]) => aliases);
const matchers = expenseTypes.flatMap(([aliases,note]) => aliases.map(alias => ({alias,note}))).sort((a,b) => b.alias.length-a.alias.length);

export function expenseItem(word) {
  // Longest phrase wins (e.g. social insurance before insurance). Qualified
  // descriptions keep the complete user wording instead of inventing details.
  const match = matchers.find(({alias}) => word.includes(alias));
  const note = match ? `总额项目：${match.note}` : '未识别费用：请补充费用用途、归属及实际金额';
  const wage=expenseTypes[0][0].includes(word);
  const name=wage?(['基本工资','管理人员工资'].includes(word)?`${word}（职工薪酬）`:'工资薪金（职工薪酬，归属待核对）'):word;
  return {category:word,name,spec:`${note}；用途及所属期间待核对；金额分配仅为拟稿`,unit:'项',totalOnly:true,recognized:Boolean(match)};
}

