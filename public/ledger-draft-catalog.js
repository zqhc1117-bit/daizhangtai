export function explicitVariant(word, catalogs) {
  // Any qualified product remains the user's original wording. A family match
  // supplies only its unit and a rough planning weight, never brand or colour.
  const entries=catalogs.flatMap(([aliases,rows])=>[
    ...aliases.map(token=>({token,rows})),
    ...rows.map(row=>({token:row[0],rows:[row]})),
  ]).map(entry=>({...entry,position:word.lastIndexOf(entry.token)})).filter(entry=>entry.position>=0)
    // The rightmost item noun wins; at the same end prefer the full name.
    // Thus 炒锅 beats 锅, 电脑 beats paper 笔记本, and 墨盒 beats 打印机.
    .sort((a,b)=>(b.position+b.token.length)-(a.position+a.token.length)||b.token.length-a.token.length);
  const family=entries[0];
  if (!family) return null;
  const suffix=word.slice(family.position+family.token.length).trimStart();
  if(/^(?:专用)?(?:包|袋|盒|支架|收纳|保护|配件|墨盒|硒鼓|盖|架|垫|刷|铲|胆|芯|头|套|把手|手柄|线|插头)/.test(suffix))return null;
  if(family.token.length===1){
    // Single-character nouns must not reinterpret 花盆/电饭锅/硬盘/奖杯.
    const prefix=word.slice(0,family.position);
    if(!/^(?:不锈钢|塑料|铝合金|铝|铁|铸铁|玻璃|陶瓷|搪瓷|硅胶|圆形|方形|大号|中号|小号|加厚|家用|厨房|深型|浅型|带盖|无盖|透明|食品级|\s)*$/.test(prefix))return null;
    if(suffix&&!/^(?:[\dA-Za-z（(]|厘米|毫米|英寸|升|毫升|加厚|带盖|无盖|圆形|方形)/.test(suffix))return null;
  }
  const score=row=>{
    const style=row[0].replace(family.token,'');
    return (word.includes(row[0])?100:0)+(style&&word.includes(style)?20:0)+row[1].split(/[ /；]+/).filter(token=>token.length>1&&word.includes(token)).length;
  };
  const ranked=[...family.rows].sort((a,b)=>score(b)-score(a)||a[3]-b[3]);
  return ranked[0];
}
